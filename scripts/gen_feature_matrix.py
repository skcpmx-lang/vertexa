#!/usr/bin/env python3
"""Generate docs/FEATURE_MATRIX.md from docs/feature_matrix.csv.

The CSV is the machine-readable source of truth (edited by hand, one row per
requirement). Statuses are validated against the allowed vocabulary so that a
typo cannot silently mark a feature as done.
"""
import csv, pathlib, sys

ALLOWED = {
    "NOT_STARTED", "PLANNED", "IN_PROGRESS", "IMPLEMENTED",
    "AUTOMATED_TEST_PASSED", "MANUAL_VERIFICATION_REQUIRED", "VERIFIED",
    "PARTIALLY_SUPPORTED", "BLOCKED", "FAILED",
}
ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "docs" / "feature_matrix.csv"
OUT = ROOT / "docs" / "FEATURE_MATRIX.md"

HEADER = ["ID", "Feature", "Pri", "Status", "Implementation", "Detection method",
          "Fallback", "Test reference", "Verification evidence", "Limitations"]


def main() -> int:
    rows = list(csv.DictReader(SRC.open(encoding="utf-8")))
    bad = [r["ID"] for r in rows if r["Status"].strip() not in ALLOWED]
    if bad:
        print(f"invalid status for: {', '.join(bad)}", file=sys.stderr)
        return 1
    counts = {}
    for r in rows:
        counts[r["Status"]] = counts.get(r["Status"], 0) + 1
    out = ["# MERQO VERTEXA — Feature Implementation Matrix", "",
           "Generated from `docs/feature_matrix.csv` by `scripts/gen_feature_matrix.py`.",
           "Do not edit this file by hand; edit the CSV and regenerate.", "",
           "**Status vocabulary:** " + " · ".join(f"`{s}`" for s in sorted(ALLOWED)), "",
           "A feature is only `VERIFIED` when automated tests pass **and** evidence is recorded.",
           "`IMPLEMENTED` means code exists and is wired but is not yet test-evidenced;",
           "`MANUAL_VERIFICATION_REQUIRED` means the code is complete but needs physical hardware.", "",
           "## Status summary", "", "| Status | Count |", "|---|---|"]
    for k in sorted(ALLOWED):
        if k in counts:
            out.append(f"| `{k}` | {counts[k]} |")
    out += [f"| **total** | **{len(rows)}** |", "",
            "## Matrix", "",
            "| " + " | ".join(HEADER) + " |",
            "|" + "|".join(["---"] * len(HEADER)) + "|"]
    for r in rows:
        cells = [r[h].replace("|", "\\|") if r[h] else "—" for h in HEADER]
        cells[0] = f"`{cells[0]}`"
        out.append("| " + " | ".join(cells) + " |")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rows)} features)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
